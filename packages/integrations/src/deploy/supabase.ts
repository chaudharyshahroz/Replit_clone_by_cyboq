/**
 * Provisioning a Supabase database for a generated application (spec §39).
 *
 * Creating a project returns a database password exactly once, at creation
 * time. It is returned to the caller and never stored by this module — the
 * caller decides where it goes, which for Reklu means the same encrypted
 * credential path everything else uses, never a log line.
 */
import { getJson, sendJson } from '../http';
import { IntegrationError } from '../types';

const API = 'https://api.supabase.com';

export interface SupabaseOrganization {
  readonly id: string;
  readonly name: string;
}

export interface SupabaseProject {
  readonly id: string;
  readonly name: string;
  readonly region: string;
  /** Supabase's own status. 'ACTIVE_HEALTHY' means ready; anything else is not. */
  readonly status: string;
}

export interface ProvisionedProject extends SupabaseProject {
  /** Shown to the user once. Reklu does not keep a plaintext copy. */
  readonly databasePassword: string;
  readonly apiUrl: string;
}

export async function listOrganizations(accessToken: string): Promise<SupabaseOrganization[]> {
  return getJson<SupabaseOrganization[]>('supabase', `${API}/v1/organizations`, accessToken);
}

export async function listProjects(accessToken: string): Promise<SupabaseProject[]> {
  return getJson<SupabaseProject[]>('supabase', `${API}/v1/projects`, accessToken);
}

/**
 * Create a project.
 *
 * The password is generated by the caller and passed in rather than invented
 * here, so the one piece of key material this function handles is chosen by
 * code that also knows where it will be stored.
 */
export async function createProject(
  accessToken: string,
  options: {
    name: string;
    organizationId: string;
    databasePassword: string;
    region?: string | undefined;
  },
): Promise<ProvisionedProject> {
  if (options.databasePassword.length < 16) {
    // A weak database password on a publicly reachable Postgres is not
    // something to accept quietly.
    throw new IntegrationError(
      'supabase',
      'The database password must be at least 16 characters.',
    );
  }

  const project = await sendJson<SupabaseProject & { endpoint?: string }>(
    'supabase',
    'POST',
    `${API}/v1/projects`,
    accessToken,
    {
      name: options.name.slice(0, 60),
      organization_id: options.organizationId,
      db_pass: options.databasePassword,
      region: options.region ?? 'us-east-1',
      plan: 'free',
    },
  );

  return {
    id: project.id,
    name: project.name,
    region: project.region,
    // Provisioning is asynchronous; the caller must poll rather than assume.
    status: project.status,
    databasePassword: options.databasePassword,
    apiUrl: `https://${project.id}.supabase.co`,
  };
}

/** Real provisioning status. A project is usable only at ACTIVE_HEALTHY. */
export async function projectStatus(accessToken: string, projectId: string): Promise<string> {
  const projects = await listProjects(accessToken);
  return projects.find((project) => project.id === projectId)?.status ?? 'UNKNOWN';
}
